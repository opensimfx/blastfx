"""Generate docs/PRESETS.md from the factory presets.  Run:  python tools/gen_preset_docs.py

Pure Python (no bpy): reads blastfx/presets/registry.py and the explosion profiles, and
derives each preset's fireball size, time unit and default shot length the same way
Create does (core.physics, core.froude).
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from blastfx.core.explosion_profile import profile_for  # noqa: E402
from blastfx.core.froude import time_unit  # noqa: E402
from blastfx.core.physics import nuclear_scale_m  # noqa: E402
from blastfx.presets.registry import _builtin_presets  # noqa: E402

GRAVITY = 9.80665
COMPONENTS = [
    ("fireball", "fireball"), ("stem", "column"), ("dust", "dust"), ("shockwave", "shockwave"),
    ("debris", "debris"), ("flash", "flash"), ("rapatronic", "rapatronic skin"),
]


def row(preset) -> str:
    d = preset.defaults
    if preset.explosion_type == "NUCLEAR" and d.get("yield_kt"):
        diameter = nuclear_scale_m(float(d["yield_kt"]))
        size = f"{diameter:.0f} m ({d['yield_kt']:g} kt)"
    else:
        diameter = float(d.get("scale", 1.0))
        size = f"{diameter:g} m"
    t_unit = time_unit(diameter / 2.0, GRAVITY)
    speed = float(d.get("speed", 1.0))
    playback = "real time" if speed == 1.0 else f"{1 / speed:.3g}x slow motion"
    parts = [label for key, label in COMPONENTS if preset.components.get(key)]
    profile = profile_for(preset.explosion_type, preset.id)
    return (f"| **{preset.label}** (`{preset.id}`) | {preset.explosion_type.title()} | {size} | {t_unit:.2f} s | "
            f"{float(d.get('duration', 0.0)):g} s ({float(d.get('duration', 0.0)) / t_unit:.1f} T) | {playback} | "
            f"{', '.join(parts)} | {profile.event_T:g} T | {preset.description} |")


def main() -> int:
    presets = list(_builtin_presets().values())
    lines = [
        "# Presets", "",
        "_Generated by `tools/gen_preset_docs.py` from `blastfx/presets/registry.py`. Do not edit by hand._", "",
        f"{len(presets)} factory presets. Size is the fireball diameter; Nuclear presets derive it from the yield. "
        "T = sqrt(R/g) is the blast's natural time unit (R = fireball radius): a bigger blast evolves more slowly in "
        "real seconds, so shot lengths are also given in T. 'Auto length' is what **Duration 0** gives. Resolution is "
        "not stored in presets: it follows from the size and the quality tier.", "",
        "| Preset | Type | Size | T | Shot | Playback | Components | Auto length | Description |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    lines += [row(p) for p in presets]
    lines += ["", "Saved presets: **Preset Files > Save as Preset** writes your settings as JSON to `presets/` next to the "
              "add-on folder (see `presets/README.md` in the repository); a saved preset cannot reuse a factory id.", ""]
    out = ROOT / "docs" / "PRESETS.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
